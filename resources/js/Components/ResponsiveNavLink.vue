<script setup>
import { computed } from 'vue';
import { Link } from '@inertiajs/vue3';

const props = defineProps({
    active: Boolean,
    href: String,
    as: String,
});

const classes = computed(() => {
    return props.active
        ? 'block w-full ps-3 pe-4 py-2 border-l-4 border-nfl-red-500 text-start text-base font-semibold text-white bg-nfl-navy-700 focus:outline-hidden focus:text-white focus:bg-nfl-navy-600 focus:border-nfl-red-400 transition duration-150 ease-in-out'
        : 'block w-full ps-3 pe-4 py-2 border-l-4 border-transparent text-start text-base font-medium text-nfl-navy-200 hover:text-white hover:bg-nfl-navy-700 hover:border-nfl-navy-400 focus:outline-hidden focus:text-white focus:bg-nfl-navy-700 focus:border-nfl-navy-400 transition duration-150 ease-in-out';
});
</script>

<template>
    <div>
        <button v-if="as == 'button'" :class="classes" class="w-full text-start">
            <slot />
        </button>

        <a v-else-if="as == 'a'" :class="classes" class="w-full text-start" :href="href">
            <slot />
        </a>

        <Link v-else :href="href" :class="classes">
            <slot />
        </Link>
    </div>
</template>
